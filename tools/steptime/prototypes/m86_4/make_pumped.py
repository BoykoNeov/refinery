"""M86.4 (docs/DESIGN.md §84.4): the two crude units whose product lines need
their pumps, generated from `scenarios/crude_unit.toml`.

    python make_pumped.py lifted  <out.toml> [overrides.json]
    python make_pumped.py grade   <out.toml> [overrides.json]

Both get the product line of `product_line_reference::crude_unit_lines` on
every draw (a 15 m fall to the pump, a water cooler, a rundown to the tank),
the 40 cm transfer line, and a check valve after each pump's discharge pipe
(Kv 400, 0.015 bar band: `draw_line_check_valve.rs`). They differ in what the
line asks of its pump:

- lifted: the tanks stand high, the rundown climbing `rise_m` to them, so the
  column cannot push its product there with the pump stopped: it stops.
- grade: the tanks stand at the column's level, as they do in a refinery, at
  the end of a long rundown; with the pump stopped the column's own pressure
  still pushes a trickle through, far less than the product's share.

`overrides.json` maps a product to any of its LINE keys, for sizing probes.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]

# Each product's cooling water [kg/s] and cooler UA [kW/K]
# (`product_line_reference::LINES`).
COOLING = {
    "naphtha": (75.0, 150.0),
    "kerosene": (115.0, 90.0),
    "diesel": (190.0, 120.0),
    "gas_oil": (150.0, 70.0),
    "residue": (460.0, 100.0),
}

# Per product: pump shutoff head h0 [m], curve a [m per (m3/s)^2], the
# rundown's length [m], diameter [m] and climb [m].
VARIANTS = {
    "lifted": {
        p: {"h0": 40.0, "a": 2000.0, "length": 100.0, "diameter": 0.15, "rise": 40.0}
        for p in COOLING
    },
    # Sized by the M86.4 probe: each line carries about 1.55 times its share
    # with its pump running, under half of it stopped.
    "grade": {
        p: {"h0": 100.0, "a": 2000.0, "length": 1500.0, "diameter": d, "rise": 15.0}
        for p, d in {
            "naphtha": 0.154,
            "kerosene": 0.131,
            "diesel": 0.14,
            "gas_oil": 0.119,
            "residue": 0.152,
        }.items()
    },
}

DESCRIPTIONS = {
    "lifted": "The crude unit with its product tanks on high ground: a stopped product pump stops its product, and the column sends it to the draw below.",
    "grade": "The crude unit with its product tanks at grade at the end of long rundowns: a stopped product pump cuts its product to under half, the rest going to the draw below.",
}

COMMON = """#
# Both M86.4 plants (docs/DESIGN.md §84.4) are `crude_unit.toml` with a
# product line on every draw: the draw falls 15 m to its pump, which pushes it
# through a check valve and a water cooler to its tank; the transfer line is
# 40 cm. The column holds no liquid, so when a line cannot carry its product
# the column sends the rest down to the draw below (§84.2): a stopped
# kerosene, diesel or gas oil pump moves its product into the next one. A
# stopped residue pump halts the run, naming the pump: there is no draw below
# the bottoms. The check valve after each pump is what keeps a tank from
# pushing its product back through a stopped pump (§84.3).
#
# The two plants teach the two halves of what a stopped centrifugal pump
# does. A stopped centrifugal pump is not a closed valve: product still flows
# through it if something else pushes (Chaudhry 2014, Table A-1: a locked
# rotor loses about half its rated head at rated flow). What stops the product
# is what the line asks the pump to lift.
"""

HEADERS = {
    "lifted": """# M86.4 demo plant: a stopped product pump STOPS its product
# (docs/DESIGN.md §84.4).
"""
    + COMMON
    + """#
# HERE THE TANKS STAND HIGH. Each rundown climbs 40 m from its pump, so every
# tank's inlet is 25 m above the column's draws. The column's own push, its
# 0.8 bar over the air outside, lifts its products only about 10-12 m above
# its draws (the lighter naphtha furthest). With the pump stopped, nothing gets up to the tank: the
# line stops, the check valve's disc shuts, and the whole product goes to the
# draw below. With the pumps running (40 m of head each) every line carries
# 1.7-3.2 times its share, so the line below can take a stopped one's.
#
# A real refinery's tanks stand at grade; tanks this high are what it takes
# to make a stopped centrifugal pump stop its product completely.
# `crude_unit_pumps_grade.toml` is the plant as refineries build it.
#
# What still halts the run: the residue pump stopped; the naphtha pump stopped
# (a column with no distillate has no reflux, and this one cannot run without
# it); or the diesel and gas oil pumps stopped together, or all three side
# pumps, whose products the residue line cannot all carry.
#
# Generated by `tools/steptime/prototypes/m86_4/make_pumped.py lifted`.
""",
    "grade": """# M86.4 demo plant: a stopped product pump CUTS its product to under half
# (docs/DESIGN.md §84.4).
"""
    + COMMON
    + """#
# HERE THE TANKS STAND AT GRADE, as in a refinery, 1.5 km away in the tank
# farm, entered 15 m up (the column's draws' level). Each pump has 100 m of
# head, the long rundown taking most of it. With the pump stopped, the
# column's 0.8 bar over the air outside still pushes product through the
# stopped pump and down the line, but that push is small against the pump's
# 100 m, so the line carries only 41-46 % of its share. The rest goes to the
# draw below. Running, each line carries 1.5-1.6 times its share.
#
# So here a stopped pump does not stop its product; it cuts it sharply. And
# the cut spreads: the diesel's rest is more than the gas oil's line can take
# on top of its own, so a stopped diesel pump runs the gas oil line at its
# limit too, and the residue takes what is left.
# `crude_unit_pumps_lifted.toml` is the same plant with its tanks on high
# ground, where a stopped pump stops its product completely.
#
# A stopped naphtha pump does not halt it here: the trickle keeps some
# distillate, and so some reflux, and the rest goes down the column. What
# still halts the run: the residue pump stopped (the trickle through it is
# less than the column's bottoms), or the diesel and gas oil pumps stopped
# together, or all three side pumps, whose products the residue line cannot
# all carry.
#
# Generated by `tools/steptime/prototypes/m86_4/make_pumped.py grade`.
""",
}


def fmt(x: float) -> str:
    s = repr(float(x))
    return s


def make(variant: str, overrides: dict) -> str:
    src = (ROOT / "scenarios" / "crude_unit.toml").read_text(encoding="utf-8")
    # Drop the original header: everything before [meta].
    src = src[src.index("[meta]"):]
    lines = {p: dict(v) for p, v in VARIANTS[variant].items()}
    for p, o in overrides.items():
        lines[p].update(o)
    stem = f"crude_unit_pumps_{variant}"
    old_meta = src[: src.index("[simulation]")]
    src = src.replace(
        old_meta,
        f'[meta]\nname = "{stem}"\ndescription = "{DESCRIPTIONS[variant]}"\n\n',
        1,
    )
    src = HEADERS[variant] + "\n" + src
    old = 'name = "transfer_line"\nfrom = "furnace"\nto = "column"\nlength_m = 15.0\ndiameter_m = 0.08'
    assert old in src
    src = src.replace(old, old.replace("0.08", "0.40"), 1)
    for p, (water, ua) in COOLING.items():
        line = lines[p]
        tank = f"{p}_tank"
        draw = f'{{ outlet = "{tank}",'
        assert draw in src, p
        src = src.replace(draw, f'{{ outlet = "{p}_pump",', 1)
        old = (
            f'name = "{p}_draw"\nfrom = "column"\nto = "{tank}"\n'
            "length_m = 20.0\ndiameter_m = 0.15"
        )
        assert old in src, p
        src = src.replace(
            old,
            f'name = "{p}_suction"\nfrom = "column"\nto = "{p}_pump"\n'
            "length_m = 20.0\ndiameter_m = 0.20\nelevation_change_m = -15.0",
            1,
        )
        src += f"""
[nodes.{p}_pump]
type = "pump"
h0_m = {fmt(line["h0"])}
a = {fmt(line["a"])}
on = true

[nodes.{p}_check]
type = "check_valve"
kv = 400.0
full_open_bar = 0.015

[nodes.{p}_cooler]
type = "water_cooler"
ua_kw_per_k = {fmt(ua)}
water_inlet_c = 30.0
water_flow_kg_per_s = {fmt(water)}

[[pipes]]
name = "{p}_discharge"
from = "{p}_pump"
to = "{p}_check"
length_m = 30.0
diameter_m = 0.15

[[pipes]]
name = "{p}_check_outlet"
from = "{p}_check"
to = "{p}_cooler"
length_m = 1.0
diameter_m = 0.15

[[pipes]]
name = "{p}_rundown"
from = "{p}_cooler"
to = "{tank}"
length_m = {fmt(line["length"])}
diameter_m = {fmt(line["diameter"])}
elevation_change_m = {fmt(line["rise"])}
"""
    return src


if __name__ == "__main__":
    variant, out = sys.argv[1], sys.argv[2]
    overrides = json.loads(pathlib.Path(sys.argv[3]).read_text()) if len(sys.argv) > 3 else {}
    pathlib.Path(out).write_text(make(variant, overrides), encoding="utf-8", newline="\n")
