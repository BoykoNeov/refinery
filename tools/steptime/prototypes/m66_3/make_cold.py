"""M66.3: scenarios/crude_unit_cold.toml from scenarios/crude_unit_stripped.toml
(docs/DESIGN.md §71.4).

The stripped crude unit at the start of a start-up: its reboiler free at the
declared reflux, its furnace low (20 MW), its pumparounds at the steamed
plant's 15/15/10 MW; the steam and the charge loop as shipped. The coil's
metal and the loop's opening are declared where this plant settles them —
measured, the two arguments — so it starts where it stays. Run from anywhere:

    python -I make_cold.py <coil_c> <opening> [out_path]
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
FURNACE_MW = 20.0

HEADER = """# M66 demo plant: the stripped crude unit before its start-up — the furnace
# low, the column on its reboiler (docs/DESIGN.md §71.4).
#
# `crude_unit_stripped.toml` (M64.3) as it stands before it is started: the
# same column, coil, steam and charge loop, at the steamed plant's own state.
#
# - THE REBOILER is free: it closes the column's energy balance at the
#   declared reflux of 4.0, about 88 MW, the bottom near 580 °C — the steamed
#   crude unit's column. A command holds it, or frees it again
#   (`SetReboilerDuty`, M66.1); held at a duty the column cannot run at, it
#   keeps the duty it ran at and says so (M66.2).
# - THE FURNACE is low, 20 MW: the crude reaches the column near 289 °C, too
#   cool for a column without its reboiler (that needs ~362 °C). Its coil
#   starts where this plant settles it, {coil:.2f} °C.
# - THE PUMPAROUNDS are the steamed plant's 15/15/10 MW; a column on its
#   reboiler with none cannot make its cold start on tick 1.
# - THE CHARGE is held on the stripped plant's flow loop at 112.8 kg/s, its
#   valve declared at the {opening} the loop settles at here.
#
# The start-up (§71.0, §71.3): the furnace to 58 MW, the pumparounds off, and
# the reboiler walked down from the duty it runs at as the feed heats — the
# column declining the steps it cannot take yet. Settled, it is
# `crude_unit_stripped.toml`.
#
# Generated by `tools/steptime/prototypes/m66_3/make_cold.py` from
# `crude_unit_stripped.toml`.
"""


def replace_once(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new, 1)


def main():
    coil = float(sys.argv[1])
    opening = float(sys.argv[2])
    out = pathlib.Path(sys.argv[3]) if len(sys.argv) > 3 else ROOT / "scenarios" / "crude_unit_cold.toml"
    src = (ROOT / "scenarios" / "crude_unit_stripped.toml").read_text(encoding="utf-8")
    body = src[src.index("[meta]"):]
    body = replace_once(body, 'name = "crude_unit_stripped"', 'name = "crude_unit_cold"')
    body = replace_once(
        body,
        'description = "The steamed crude unit stripped by its steam alone: the reboiler held at zero, the reflux a result, the furnace carrying the heat and the charge held on a flow loop."',
        'description = "The stripped crude unit before its start-up: the furnace low at 20 MW, the column on its reboiler at a reflux of 4, the pumparounds on; started by commands to the stripped plant."',
    )
    body = replace_once(body, "reboiler_duty_mw = 0.0\n", "")
    body = replace_once(body, "duty_mw = 58.0\n", f"duty_mw = {FURNACE_MW}\n")
    body = replace_once(body, "coil_temperature_c = 436.88\n", f"coil_temperature_c = {coil}\n")
    body = replace_once(
        body,
        "pumparounds = [{ stage = 4, duty_mw = 0.0 }, { stage = 6, duty_mw = 0.0 }, { stage = 7, duty_mw = 0.0 }]",
        "pumparounds = [{ stage = 4, duty_mw = 15.0 }, { stage = 6, duty_mw = 15.0 }, { stage = 7, duty_mw = 10.0 }]",
    )
    body = replace_once(body, "kv = 400.0\nopening = 0.419\n", f"kv = 400.0\nopening = {opening}\n")
    body = replace_once(body, "initial_output = 0.419\n", f"initial_output = {opening}\n")
    out.write_text(HEADER.format(coil=coil, opening=opening) + "\n" + body, encoding="utf-8", newline="\n")
    print(f"written {out}")


main()
