"""M65.4: scenarios/crude_unit_wetter.toml from scenarios/crude_unit_wet.toml.

The wet crude unit's crude at 2 % water by mass, its oil scaled to 98 %; the
furnace coil's metal declared at the temperature this plant settles it at
(measured, the first argument, °C); everything else as shipped. Run from
anywhere:

    python make_wetter_plant.py <coil_c> [out_path]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
WATER = 0.02
OIL = [
    ("light_naphtha", 0.07976),
    ("heavy_naphtha", 0.13958),
    ("kerosene", 0.15952),
    ("diesel", 0.1994),
    ("gas_oil", 0.13958),
    ("residue", 0.27916),
]

HEADER = """# M65 demo plant: the wet crude unit on a wetter crude, 2 % water — a desalter
# upset (docs/DESIGN.md §70.4).
#
# `crude_unit_wet.toml` (M62.5, 0.3 % water) with its crude at 2 % water by
# mass, the oil scaled to make room:
#
# - THE CHARGE falls: the supply boils harder at its 270 °C and 30 bar, so the
#   fixed control valve and the coil pass a stream with more vapour in it —
#   about 75 kg/s against the shipped plant's 113. With the furnace at its 20
#   MW the coil runs hotter; its metal starts where this plant settles it,
#   {coil:.2f} °C.
# - THE COLUMN STARTS on tick 1 at the shipped 40 MW of pumparounds only by
#   M65.1's retry: started cold, it runs only from about 0.45 to 0.95 of them
#   at this charge, so it starts from half and walks them back (§70.1).
#   Running, it takes any of them.
# - THE WATER, 2 % of the charge, rides up the column as vapour and is
#   decanted at the condenser to the sour-water tank, as on the wet plant.
#
# Generated by `tools/steptime/prototypes/m65_4/make_wetter_plant.py` from
# `crude_unit_wet.toml`.
"""


def main():
    coil = float(sys.argv[1])
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "scenarios" / "crude_unit_wetter.toml"
    src = (ROOT / "scenarios" / "crude_unit_wet.toml").read_text(encoding="utf-8")
    body = src[src.index("[meta]"):]
    total = sum(f for _, f in OIL)
    parts = ", ".join(f"{name} = {round(f / total * (1 - WATER), 6)}" for name, f in OIL)
    body, n = re.subn(
        r"composition = \{ light_naphtha = 0\.07976[^}]*\}",
        "composition = { " + parts + f", water = {WATER} }}",
        body,
        count=1,
    )
    assert n == 1
    body = body.replace('name = "crude_unit_wet"', 'name = "crude_unit_wetter"')
    body = re.sub(
        r'description = "[^"]*"',
        'description = "The wet crude unit on a wetter crude, 2 % water: the charge falls as the supply boils harder, and the column starts on tick 1 by walking its pumparounds back from half."',
        body,
        count=1,
    )
    body, n = re.subn(r"coil_temperature_c = [0-9.]+", f"coil_temperature_c = {coil:.2f}", body, count=1)
    assert n == 1
    out.write_text(HEADER.format(coil=coil) + "\n" + body, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
